drop database QUANLYCUAHANG;
CREATE DATABASE QUANLYCUAHANG CHAR SET utf8mb4;

DROP TABLE IF EXISTS KHACHHANG;
CREATE TABLE IF NOT EXISTS KHACHHANG
(
	MAKH VARCHAR(10),
    TENKH VARCHAR(100) NOT NULL,
    DAICHI VARCHAR(100),
    SODT VARCHAR(20),
    MASOTHUE VARCHAR(20) UNIQUE,
    PRIMARY KEY (MAKH)
);

DROP TABLE IF EXISTS MUCTIENGIO;
CREATE TABLE IF NOT EXISTS MUCTIENGIO
(
	MATIENGIO VARCHAR(10),
    DONGIA DECIMAL(10, 2) NOT NULL,
    MOTA VARCHAR(100),
    PRIMARY KEY (MATIENGIO)
);

DROP TABLE IF EXISTS PHONG;
CREATE TABLE IF NOT EXISTS PHONG
(
	MAPHONG VARCHAR(10),
    SOKHACHTOIDA INT NOT NULL,
    TRANGTHAI VARCHAR(100),
    MOTA VARCHAR(100),
     PRIMARY KEY (MAPHONG)
);

DROP TABLE IF EXISTS DICHVU;
CREATE TABLE IF NOT EXISTS DICHVU
(
	MADV VARCHAR(10),
    TENDICHVU VARCHAR(100) NOT NULL,
    DONVITINH VARCHAR(20),
    DONGIA DECIMAL(10, 2),
     PRIMARY KEY (MADV)
);

DROP TABLE IF EXISTS HOADON;
CREATE TABLE IF NOT EXISTS HOADON
(
	MAHD VARCHAR(10),
    MAKH VARCHAR(10) NOT NULL,
    MAPHONG VARCHAR(10) NOT NULL,
    MATIENGIO VARCHAR(10) NOT NULL,
    THOIGIANBATDAUSD  DATETIME NOT NULL DEFAULT current_timestamp(),
    THOIGIANKETTHUCSD  DATETIME NOT NULL DEFAULT current_timestamp(),
    TRANGTHAIHD VARCHAR(100),
     PRIMARY KEY (MAHD),
     CONSTRAINT FK_HOADON_KHACHHANG
		FOREIGN KEY (MAKH) REFERENCES KHACHHANG(MAKH),
        CONSTRAINT FK_HOADON_PHONG
		FOREIGN KEY (MAPHONG) REFERENCES PHONG(MAPHONG),
        CONSTRAINT FK_HOADON_MUCTIENGIO
		FOREIGN KEY (MATIENGIO) REFERENCES MUCTIENGIO(MATIENGIO)
);

DROP TABLE IF EXISTS CHITIET_SUDUNGDV;
CREATE TABLE IF NOT EXISTS CHITIET_SUDUNGDV
(
	MAHD VARCHAR(10),
    MADV VARCHAR(10) NOT NULL,
    SOLUONG INT NOT NULL,
     PRIMARY KEY (MAHD,MADV),
     CONSTRAINT FK_CHITIET_SUDUNGDV_HOADON
		FOREIGN KEY (MAHD) REFERENCES HOADON(MAHD),
        CONSTRAINT FK_CHITIET_SUDUNGDV_DICHVU
		FOREIGN KEY (MADV) REFERENCES DICHVU(MADV)
);


