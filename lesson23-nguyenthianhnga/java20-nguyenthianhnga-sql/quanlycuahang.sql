/* --- Liệt kê các phòng karaoke được sử dụng nhiều nhất từ 02.2014 đến 02.2015 */

SELECT p.MAPHONG, 
	   p.MOTA, 
       COUNT(h.MAHD) AS SO_LUONG_SU_DUNG
  FROM HOADON h
  JOIN PHONG p ON h.MAPHONG = p.MAPHONG
  WHERE h.THOIGIANBATDAUSD >= '2014-02-01' AND 
		h.THOIGIANBATDAUSD < '2015-03-01'
  GROUP BY p.MAPHONG, p.MOTA
  ORDER BY SO_LUONG_SU_DUNG DESC;
  
  /* Liệt kê 2 dịch vụ được sử dụng nhiều nhất trong mỗi tháng từ 01.2014 đến 12.2014 */
  
SELECT MONTH(h.THOIGIANBATDAUSD) AS THANG,
       dv.MADV, 
       dv.TENDICHVU, 
       SUM(cs.SOLUONG) AS TONG_SO_LUONG
 FROM CHITIET_SUDUNGDV cs
 JOIN HOADON h 
	ON cs.MAHD = h.MAHD
 JOIN DICHVU dv 
	ON cs.MADV = dv.MADV
 WHERE h.THOIGIANBATDAUSD >= '2014-01-01' AND 
       h.THOIGIANBATDAUSD < '2015-01-01'
GROUP BY MONTH(h.THOIGIANBATDAUSD), dv.MADV, dv.TENDICHVU
ORDER BY THANG, 
         TONG_SO_LUONG DESC;
    

